local q = _hypr.find_bind("SUPER + Q")
assert(q, "There's no bind for SUPER + Q.")
assert(q.action.dispatcher == "exec_cmd" and q.action.args == "kitty", "SUPER + Q should run hl.dsp.exec_cmd(terminal).")
local e = _hypr.find_bind("SUPER + E")
assert(e, "There's no bind for SUPER + E.")
assert(e.action.dispatcher == "exec_cmd" and e.action.args == "dolphin", "SUPER + E should run the fileManager.")
local c = _hypr.find_bind("SUPER + C")
assert(c, "There's no bind for SUPER + C.")
assert(c.action.dispatcher == "window.close", "SUPER + C should use hl.dsp.window.close().")
